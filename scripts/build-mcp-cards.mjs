// Builds the Fabric MCP cards view (src/mcp-cards) into one self-contained HTML
// document and writes it to convex/mcp/cardsHtml.generated.ts, which the MCP
// server serves as `ui://fabric/cards` (Phase 5). Run after changing
// src/mcp-cards: `node scripts/build-mcp-cards.mjs`. A test fails when the
// committed module is stale.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspace = path.resolve(process.cwd());
const source = path.join(workspace, "src/mcp-cards");
const output = path.join(workspace, "convex/mcp/cardsHtml.generated.ts");

export async function renderCardsHtml() {
  const bundle = await build({
    entryPoints: [path.join(source, "app.ts")],
    bundle: true,
    write: false,
    format: "iife",
    target: "es2020",
    minify: true,
    legalComments: "none",
    logLevel: "silent",
  });
  const script = bundle.outputFiles[0].text.trim();
  const css = (await readFile(path.join(source, "styles.css"), "utf8")).trim();
  // Inline script and style only: no external origins, so the host's default CSP applies.
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    "<title>Fabric</title>",
    `<style>${css}</style>`,
    "</head>",
    "<body>",
    '<div id="root"></div>',
    `<script>${script.replace(/<\/script/gi, "<\\/script")}</script>`,
    "</body>",
    "</html>",
  ].join("\n");
}

export function renderModule(html) {
  return [
    "// Generated by scripts/build-mcp-cards.mjs from src/mcp-cards. Do not edit.",
    "/** The Fabric MCP cards view, served as `ui://fabric/cards` (text/html;profile=mcp-app). */",
    `export const MCP_CARDS_HTML = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
}

// Write only when run as a script; tests import the functions above.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = await renderCardsHtml();
  await writeFile(output, renderModule(html));
  console.log(`Wrote ${path.relative(workspace, output)} (${(html.length / 1024).toFixed(1)} KB)`);
}
