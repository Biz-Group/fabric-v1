/**
 * Compiles the product help corpus (`src/content/help/*.md`) into the module
 * AskFabric's help tool reads (FR-1.18, D36). Pure: the build script feeds it
 * files from disk, and a test feeds it the same files to check the committed
 * module is current. Erasable TypeScript only, so Node runs it directly.
 */

export const HELP_AUDIENCES = ["viewer", "contributor", "admin"] as const;
export type HelpAudience = (typeof HELP_AUDIENCES)[number];

export type HelpArticle = {
  id: string;
  title: string;
  summary: string;
  audience: HelpAudience[];
  tags: string[];
  related: string[];
  body: string;
};

export const MIN_BODY_WORDS = 150;
export const MAX_BODY_WORDS = 450;

const NOT_ARTICLES = new Set(["README", "REVIEW-NOTES"]);

/** The small YAML subset the articles use: scalars, `[a, b]` and `- item` lists. */
export function parseFrontmatter(source: string): { data: Record<string, string | string[]>; body: string } {
  const text = source.replace(/\r\n/g, "\n");
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) throw new Error("missing frontmatter");
  const data: Record<string, string | string[]> = {};
  let listKey: string | null = null;
  for (const line of match[1].split("\n")) {
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && listKey) {
      (data[listKey] as string[]).push(item[1].trim());
      continue;
    }
    const pair = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (!pair) continue;
    const [, key, raw] = pair;
    const value = raw.trim();
    if (value === "") {
      data[key] = [];
      listKey = key;
    } else if (value.startsWith("[") && value.endsWith("]")) {
      data[key] = value
        .slice(1, -1)
        .split(",")
        .map((v) => v.trim())
        .filter(Boolean);
      listKey = null;
    } else {
      data[key] = value.replace(/^["']|["']$/g, "");
      listKey = null;
    }
  }
  return { data, body: match[2].trim() };
}

/** Article ids with an open `## <id>` section in REVIEW-NOTES.md; other headings are ignored. */
export function gatedIds(reviewNotes: string, articleIds: ReadonlySet<string>): Set<string> {
  const gated = new Set<string>();
  for (const line of reviewNotes.replace(/\r\n/g, "\n").split("\n")) {
    const heading = line.match(/^##\s+(.+?)\s*$/);
    if (heading && articleIds.has(heading[1])) gated.add(heading[1]);
  }
  return gated;
}

export function wordCount(text: string): number {
  return text.split(/\s+/).filter(Boolean).length;
}

/**
 * Builds the corpus from `{ fileName: contents }` (file names like
 * `label-speakers.md`) and REVIEW-NOTES.md. Gated articles are left out
 * before validation, so an article under review can't break the build.
 */
export function buildHelpCorpus(
  files: Record<string, string>,
  reviewNotes: string,
): { articles: HelpArticle[]; excluded: string[] } {
  const entries = Object.entries(files)
    .map(([name, contents]) => [name.replace(/^.*[\\/]/, "").replace(/\.md$/, ""), contents] as const)
    .filter(([id]) => !NOT_ARTICLES.has(id))
    .sort(([a], [b]) => a.localeCompare(b));
  const gated = gatedIds(reviewNotes, new Set(entries.map(([id]) => id)));

  const articles: HelpArticle[] = [];
  for (const [id, contents] of entries) {
    if (gated.has(id)) continue;
    const { data, body } = parseFrontmatter(contents);
    const fail = (problem: string) => {
      throw new Error(`help article ${id}: ${problem}`);
    };
    const str = (key: string) => {
      const value = data[key];
      if (typeof value !== "string" || !value) fail(`missing ${key}`);
      return value as string;
    };
    const list = (key: string) => {
      const value = data[key];
      if (!Array.isArray(value)) fail(`${key} must be a list`);
      return value as string[];
    };
    if (str("id") !== id) fail(`frontmatter id "${data.id}" does not match the file name`);
    const audience = list("audience");
    if (audience.length === 0 || audience.some((a) => !(HELP_AUDIENCES as readonly string[]).includes(a))) {
      fail(`audience must be some of ${HELP_AUDIENCES.join(", ")}`);
    }
    list("verifiedAgainst");
    const words = wordCount(body);
    if (words < MIN_BODY_WORDS || words > MAX_BODY_WORDS) {
      fail(`body has ${words} words; it must be ${MIN_BODY_WORDS}–${MAX_BODY_WORDS}`);
    }
    articles.push({
      id,
      title: str("title"),
      summary: str("summary"),
      audience: audience as HelpAudience[],
      tags: list("tags"),
      related: list("related"),
      body,
    });
  }
  return { articles, excluded: [...gated].sort() };
}

/** The generated module's exact text. */
export function renderHelpCorpusModule(corpus: { articles: HelpArticle[]; excluded: string[] }): string {
  return [
    "// Generated by scripts/build-help-corpus.mjs from src/content/help/. Do not edit;",
    "// run `node scripts/build-help-corpus.mjs` after changing an article.",
    'import type { HelpArticle } from "./helpCorpusBuild";',
    "",
    `/** Left out while REVIEW-NOTES.md has open items for them. */`,
    `export const EXCLUDED_HELP_ARTICLES: readonly string[] = ${JSON.stringify(corpus.excluded)};`,
    "",
    `export const HELP_ARTICLES: readonly HelpArticle[] = ${JSON.stringify(corpus.articles, null, 2)};`,
    "",
  ].join("\n");
}
