import { Button as ButtonPrimitive } from "@base-ui/react/button"
import { cva, type VariantProps } from "class-variance-authority"

import { cn } from "@/lib/utils"

// Each size sets its own icon size for svgs without a `size-*` class. The
// default lives on the sizes, not the base: at equal specificity the compiled
// `size-4` rule sorts after `size-3`/`size-3.5`, so a base default silently
// beat the xs/sm ones. An icon with its own `size-*` class keeps it.
